-- Faz 8: Bekleme listesi (plan §10.10) — hiç uygulanmamıştı.

CREATE TABLE waitlist (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version          BIGINT      NOT NULL DEFAULT 0,
    branch_id        BIGINT      NOT NULL DEFAULT 1,
    deleted          BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP   NOT NULL,
    created_by       VARCHAR(100),
    updated_at       TIMESTAMP   NOT NULL,
    updated_by       VARCHAR(100),
    party_id         BIGINT       NOT NULL,
    service_id       BIGINT       NOT NULL,
    staff_party_id   BIGINT,
    preferred_from   TIMESTAMP,
    preferred_to     TIMESTAMP,
    notes            VARCHAR(500),
    status           VARCHAR(20)  NOT NULL DEFAULT 'BEKLEMEDE',
    appointment_id   BIGINT,
    CONSTRAINT fk_waitlist_service FOREIGN KEY (service_id) REFERENCES service_definition (id)
);
CREATE INDEX ix_waitlist_status ON waitlist (status, created_at);
CREATE INDEX ix_waitlist_party ON waitlist (party_id);
