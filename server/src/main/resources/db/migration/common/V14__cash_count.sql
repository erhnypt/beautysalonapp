CREATE TABLE cash_count (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version           BIGINT      NOT NULL DEFAULT 0,
    branch_id         BIGINT      NOT NULL DEFAULT 1,
    deleted           BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMP   NOT NULL,
    created_by        VARCHAR(100),
    updated_at        TIMESTAMP   NOT NULL,
    updated_by        VARCHAR(100),
    account_id        BIGINT        NOT NULL,
    count_date        DATE          NOT NULL,
    expected_amount   NUMERIC(19,4) NOT NULL,
    counted_amount    NUMERIC(19,4) NOT NULL,
    difference        NUMERIC(19,4) NOT NULL,
    reason            VARCHAR(300),
    adjustment_doc_no VARCHAR(40)
);
CREATE INDEX ix_cash_count_account ON cash_count (account_id, count_date);
